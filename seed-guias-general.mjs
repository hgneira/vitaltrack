const norm = s => s.toLowerCase().trim()
  .replace(/á/g,"a").replace(/é/g,"e").replace(/í/g,"i").replace(/ó/g,"o").replace(/ú/g,"u")
  .replace(/ñ/g,"n").replace(/ü/g,"u");

function getPasos(nombre) {
  const n = norm(nombre);
  // exact match
  if (GUIAS[n]) return GUIAS[n];
  // partial match
  for (const [key, pasos] of Object.entries(GUIAS)) {
    if (n.includes(norm(key)) || norm(key).includes(n)) return pasos;
  }
  return null;
}

async function main() {
  const equipos = await prisma.equipoMedico.findMany({
    select: { id: true, nombre: true, marca: true, modelo: true },
  });

  console.log(`📋 Procesando ${equipos.length} equipos…\n`);
  let creados = 0;
  let actualizados = 0;
  let sinGuia = 0;

  for (const eq of equipos) {
    const pasos = getPasos(eq.nombre);
    if (!pasos) { sinGuia++; continue; }

    const existing = await prisma.guiaRapida.findUnique({ where: { equipoId: eq.id } });
    if (existing) {
      await prisma.guiaRapida.update({ where: { equipoId: eq.id }, data: { pasos } });
      actualizados++;
    } else {
      await prisma.guiaRapida.create({ data: { equipoId: eq.id, pasos } });
      creados++;
    }
    process.stdout.write(`  ✓ ${eq.nombre}\n`);
  }

  console.log(`\n✅ Guías creadas: ${creados}  |  Actualizadas: ${actualizados}  |  Sin guía: ${sinGuia}`);
}

main()
  .catch(e => { console.error(e); process.exit(1); })
  .finally(() => prisma.$disconnect());
